import { chromium } from "playwright";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const errs = [];
page.on("pageerror", (e) => errs.push(e.message));
page.on("console", (m) => { if (m.type() === "error") errs.push(m.text()); });
await page.goto(process.argv[2], { waitUntil: "domcontentloaded", timeout: 90000 });
await page.waitForFunction(() => !!window.__game, null, { timeout: 30000 });
await page.waitForTimeout(500);
await page.evaluate(() => { window.__game.S.energy = 100; window.__game.paintFin && window.__game.paintFin(); });
const r0 = await page.evaluate(() => window.__game.dbg().round);
await page.evaluate(() => window.__game.chooseMove(window.__game.S.skills.length));
await page.waitForTimeout(400);
const mid = await page.evaluate(() => window.__game.dbg().phase);
await page.waitForFunction(() => window.__game.dbg().phase === "plan", null, { timeout: 30000 }).catch(() => {});
const fin = await page.evaluate(() => window.__game.dbg());
console.log(JSON.stringify({ mid, afterPhase: fin.phase, roundBefore: r0, roundAfter: fin.round, energy: fin.energy, hp: fin.hp, foeHp: fin.foes.map(f => f.hp) }));
console.log("errors:", errs.length ? errs.slice(0, 4) : "none");
await browser.close();
